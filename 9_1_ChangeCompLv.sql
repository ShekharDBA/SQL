
DECLARE @DBNAME NVARCHAR(200)
DECLARE @CompLvl int

DECLARE getDB CURSOR FOR 
Select name,cmptlevel from sys.sysdatabases Where cmptlevel<>160
OPEN getDB
FETCH NEXT FROM getDB INTO @DBNAME,@CompLvl
WHILE @@FETCH_STATUS=0
BEGIN
DECLARE @SQL NVARCHAR(MAX)
SET @SQL='
USE [master]
ALTER DATABASE ['+@DBNAME+'] SET COMPATIBILITY_LEVEL = 160
'
--PRINT(@SQL)
PRINT(@DBNAME+' COMPATIBILITY_LEVEL Changed From '+CONVERT(VARCHAR(20),@CompLvl)+' TO 160')
EXEC(@SQL)
FETCH NEXT FROM getDB INTO @DBNAME,@CompLvl
END
CLOSE getDB
DEALLOCATE getDB



